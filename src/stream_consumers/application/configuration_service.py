"""Which credentials and settings the sources read, which keys are held, whether each is set, and a `.env` template."""

from __future__ import annotations

from collections.abc import Sequence

from stream_consumers.domain.models import ConfigKind, ConfigStatus, Credential, SourceDescriptor
from stream_consumers.ports.inbound import DescribeConfigurationUseCase
from stream_consumers.ports.outbound.providers import HeldKeyCatalogPort, SourceRegistryPort
from stream_consumers.ports.outbound.system import SecretProviderPort

TEMPLATE_HEADER = """\
# stream-consumers configuration. Copy to .env (git-ignored) and fill in what you have.
# Generated by `stream-consumers keys --template`; tests/unit/test_configuration.py keeps
# .env.example identical to it. Values set in the process environment win over this file.
#
# A source whose REQUIRED credentials are missing reports `key-pending` and is skipped;
# OPTIONAL credentials only raise a provider's limits. Settings show their default.
"""

HELD_HEADER = """\
# ===== Held keys: no source reads them; they are kept so each can be tested again
# (tests/live/test_keys_live.py checks that each is accepted and that a damaged copy is refused).
"""


OUTPUTS = "--out"
"""The `source_id` of the rows for credentials read by output destinations rather than by a source."""


class ConfigurationService(DescribeConfigurationUseCase):
    """`outputs` are credentials the output destinations read (e.g. a database password)."""

    def __init__(
        self, registry: SourceRegistryPort, environment: SecretProviderPort, held: HeldKeyCatalogPort, outputs: Sequence[Credential] = ()
    ) -> None:
        self._registry = registry
        self._environment = environment
        self._held = held
        self._outputs = tuple(outputs)
        held_names = {n for k in held.held_keys() for n in k.env_vars}
        clash = sorted(self._source_variables() & held_names)
        if clash:
            raise ValueError(f"held keys must not be variables a source reads: {', '.join(clash)}")
        clash = sorted(self._output_variables() & (self._source_variables() | held_names))
        if clash:
            raise ValueError(f"output credentials must not be variables a source reads or held keys: {', '.join(clash)}")

    def _output_variables(self) -> set[str]:
        return {n for c in self._outputs for n in c.env_vars}

    def _source_variables(self) -> set[str]:
        declared = {s.env_var for d in self._registry.descriptors() for s in d.settings}
        return declared | {n for d in self._registry.descriptors() if d.credential for n in d.credential.env_vars}

    def _configurable(self) -> list[SourceDescriptor]:
        return sorted((d for d in self._registry.descriptors() if d.credential or d.settings), key=lambda d: d.id)

    def status(self) -> Sequence[ConfigStatus]:
        out: list[ConfigStatus] = []
        for d in self._configurable():
            if d.credential is not None:
                out += [
                    ConfigStatus(
                        d.id,
                        name,
                        ConfigKind.SECRET,
                        d.credential.required,
                        self._environment.get(name) is not None,
                        sign_up_url=d.credential.sign_up_url,
                        description=d.credential.how_to_get,
                    )
                    for name in d.credential.env_vars
                ]
            out += [
                ConfigStatus(
                    d.id,
                    s.env_var,
                    ConfigKind.SETTING,
                    False,
                    self._environment.get(s.env_var) is not None,
                    default=s.default,
                    description=s.description,
                )
                for s in d.settings
            ]
        out += [
            ConfigStatus(
                OUTPUTS,
                name,
                ConfigKind.SECRET,
                False,
                self._environment.get(name) is not None,
                sign_up_url=c.sign_up_url,
                description=c.how_to_get,
            )
            for c in self._outputs
            for name in c.env_vars
        ]
        out += [
            ConfigStatus(
                k.owner,
                name,
                ConfigKind.HELD,
                False,
                self._environment.get(name) is not None,
                sign_up_url=k.sign_up_url,
                description=k.purpose,
            )
            for k in self._held.held_keys()
            for name in k.env_vars
        ]
        return out

    def unknown_variables(self) -> Sequence[str]:
        declared = self._source_variables() | self._output_variables() | {n for k in self._held.held_keys() for n in k.env_vars}
        return [name for name in self._environment.file_names() if name not in declared]

    def env_template(self) -> str:
        blocks = [TEMPLATE_HEADER]
        for d in self._configurable():
            lines = [f"# --- {d.id}: {d.name} ({d.provider})"]
            if d.credential is not None:
                need = "REQUIRED" if d.credential.required else "OPTIONAL (the source also works without it)"
                lines.append(f"# Credentials {need}. Sign-up: {d.credential.sign_up_url}")
                if d.credential.how_to_get:
                    lines.append(f"# How: {d.credential.how_to_get}")
                lines += [f"{name}=" for name in d.credential.env_vars]
            for s in d.settings:
                lines.append(f"# {s.description} Default: {s.default or '(empty)'}")
                lines.append(f"# {s.env_var}={s.default}")
            blocks.append("\n".join(lines) + "\n")
        for c in self._outputs:
            lines = [f"# --- {OUTPUTS}: credentials of output destinations ({c.sign_up_url})", f"# How: {c.how_to_get}"]
            blocks.append("\n".join(lines + [f"{name}=" for name in c.env_vars]) + "\n")
        if self._held.held_keys():
            blocks.append(HELD_HEADER)
        for k in self._held.held_keys():
            lines = [f"# --- {k.owner}: {k.provider}. {k.purpose}", f"# Sign-up: {k.sign_up_url}"]
            blocks.append("\n".join(lines + [f"{name}=" for name in k.env_vars]) + "\n")
        return "\n".join(blocks)
